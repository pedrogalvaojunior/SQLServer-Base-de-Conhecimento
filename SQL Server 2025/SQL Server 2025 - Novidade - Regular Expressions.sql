------------------------------------------------------------------------------
-- Introdução
--
-- Expressões Regulares permitem localizar padrões
-- utilizando uma linguagem específica.
--
-- Exemplos:
--
-- E-mails
-- Telefones
-- CEP
-- CPF
-- CNPJ
-- URLs
-- Datas
-- Códigos de Produto
------------------------------------------------------------------------------
GO

------------------------------------------------------------------------------
-- Ambiente de Demonstração
------------------------------------------------------------------------------

DROP TABLE IF EXISTS dbo.ExemplosRegex;
GO

CREATE TABLE dbo.ExemplosRegex
(
    IdRegistro          INT IDENTITY(1,1)
                        CONSTRAINT PK_ExemplosRegex
                        PRIMARY KEY,

    Texto               VARCHAR(200)
                        NOT NULL
);
GO

------------------------------------------------------------------------------
-- Inserção dos Dados
------------------------------------------------------------------------------

INSERT INTO dbo.ExemplosRegex
(
    Texto
)
VALUES
('pedro@empresa.com.br'),
('(11)99999-9999'),
('18130-000'),
('ABC-2025-001'),
('https://www.microsoft.com'),
('CPF 123.456.789-00'),
('SQL Server 2025');
GO

------------------------------------------------------------------------------
-- Visualização Inicial
------------------------------------------------------------------------------

SELECT
    ER.IdRegistro,
    ER.Texto
FROM dbo.ExemplosRegex AS ER;
GO

------------------------------------------------------------------------------
-- Classes de Caracteres
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- [0-9]
--
-- Representa qualquer dígito.
--
-- Exemplos:
--
-- 0
-- 1
-- 2
-- 9
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- [A-Z]
--
-- Letras maiúsculas.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- [a-z]
--
-- Letras minúsculas.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- [A-Za-z]
--
-- Qualquer letra.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- [A-Za-z0-9]
--
-- Letras ou números.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- Caracteres Especiais
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- .
--
-- Qualquer caractere.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- ^
--
-- Início da string.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- $
--
-- Final da string.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- Quantificadores
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- *
--
-- Zero ou mais ocorrências.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- +
--
-- Uma ou mais ocorrências.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- ?
--
-- Zero ou uma ocorrência.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- {3}
--
-- Exatamente 3 ocorrências.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- {2,5}
--
-- Entre 2 e 5 ocorrências.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- Exemplos Conceituais
------------------------------------------------------------------------------

/*

CEP Brasileiro

^[0-9]{5}-[0-9]{3}$


Telefone Celular

^\([0-9]{2}\)[0-9]{5}-[0-9]{4}$


Código Produto

^[A-Z]{3}-[0-9]{4}-[0-9]{3}$


E-mail

^[A-Za-z0-9._%+-]+@
[A-Za-z0-9.-]+\.
[A-Za-z]{2,}$

*/

------------------------------------------------------------------------------
-- Classes Pré-Definidas
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- \d
--
-- Representa dígitos.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- \w
--
-- Letras, números e underscore.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- \s
--
-- Espaços em branco.
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- Exemplos Conceituais
------------------------------------------------------------------------------

/*

\d+

12345


[A-Z]+

SQL
SERVER


\d{2}/\d{2}/\d{4}

17/09/2026

*/

------------------------------------------------------------------------------
-- Agrupamentos
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- ()
--
-- Criação de grupos.
------------------------------------------------------------------------------

/*

(ABC|XYZ)

ABC
XYZ


(SP|RJ|MG)

SP
RJ
MG

*/

------------------------------------------------------------------------------
-- Alternância
------------------------------------------------------------------------------

------------------------------------------------------------------------------
-- |
--
-- Operador OR
------------------------------------------------------------------------------

/*

SQL|Oracle|PostgreSQL

*/

------------------------------------------------------------------------------
-- Comparação com LIKE
------------------------------------------------------------------------------

SELECT
    Texto
FROM dbo.ExemplosRegex
WHERE Texto LIKE '%SQL%';
GO

------------------------------------------------------------------------------
-- Comparação com PATINDEX
------------------------------------------------------------------------------

SELECT
    Texto
FROM dbo.ExemplosRegex
WHERE PATINDEX
(
    '%[0-9]%',
    Texto
) > 0;
GO

